import test from 'node:test';
import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { mkdtemp, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import { startFakeServices, syntheticEmbedding } from './fake-services.mjs';

test('synthetic rollout drives real sync CLI and MCP stdio through HTTP adapters', { timeout: 30000 }, async () => {
  const fake = await startFakeServices();
  const root = await mkdtemp(join(tmpdir(), 'research-rehearsal-'));
  const env = { SystemRoot: process.env.SystemRoot, ...fake.env, RESEARCH_ROOT: root };
  const syncScript = fileURLToPath(new URL('../src/sync.mjs', import.meta.url));
  const run = promisify(execFile);
  const sync = () => run(process.execPath, [syncScript], { env, timeout: 5000 });
  const note = (title, body) => `---\nproject: CIC\ntitle: ${title}\nstatus: VERIFIED\n---\n${body}`;
  let client;
  let transport;
  let childPid;
  try {
    await writeFile(join(root, 'cic.md'), note('Original', 'First.\n\nSecond.\n\nThird.'));
    await writeFile(join(root, 'drive.md'), '---\nproject: RewriteLabs\ndrive_file_id: synthetic-export\nstatus: VERIFIED\n---\nDrive body.');
    const dry = await run(process.execPath, [syncScript, '--dry-run'], { env: { SystemRoot: env.SystemRoot, RESEARCH_ROOT: root }, timeout: 5000 });
    assert.equal(JSON.parse(dry.stderr).processed, 2);
    assert.equal(fake.state.requests.length, 0);
    assert.equal(JSON.parse((await sync()).stderr).processed, 2);
    assert.equal(fake.state.items.length, 4);
    const first = fake.state.documents.get('CIC:cic.md');
    const survivor = fake.state.items.find(row => row.document_id === first.id && row.chunk_index === 0).id;
    const values = fake.state.items.filter(row => row.document_id === first.id).map(row => row.embedding);
    assert.deepEqual(values, ['First.', 'Second.', 'Third.'].map(syntheticEmbedding));
    await sync();
    assert.equal(fake.state.documents.size, 2);
    assert.equal(fake.state.items.length, 4);
    await writeFile(join(root, 'cic.md'), note('Metadata edit', 'First.\n\nSecond.\n\nThird.'));
    await sync();
    assert.equal(fake.state.documents.get('CIC:cic.md').title, 'Metadata edit');
    await writeFile(join(root, 'cic.md'), note('Shorter', 'First.'));
    await sync();
    assert.equal(fake.state.items.filter(row => row.document_id === first.id).length, 1);
    assert.equal(fake.state.items.find(row => row.document_id === first.id).id, survivor);
    const snapshot = JSON.stringify([...fake.state.documents]);
    fake.state.embeddingFailure = true;
    await assert.rejects(sync(), error => error.code === 1 && JSON.parse(error.stderr).failed === 2);
    assert.equal(JSON.stringify([...fake.state.documents]), snapshot);
    fake.state.embeddingFailure = false;
    fake.state.writeFailure = true;
    await assert.rejects(sync(), error => error.code === 1 && JSON.parse(error.stderr).failed === 2);
    assert.equal(JSON.stringify([...fake.state.documents]), snapshot);
    fake.state.writeFailure = false;
    fake.state.claims.push({ id: 'claim', project: 'CIC', document_id: first.id, statement: 'Synthetic claim' });

    const reader = fake.sign('CIC');
    const readerEnv = { SystemRoot: env.SystemRoot, ...fake.env, SUPABASE_READER_JWT: reader };
    delete readerEnv.SUPABASE_SERVICE_ROLE_KEY;
    transport = new StdioClientTransport({ command: process.execPath, args: [fileURLToPath(new URL('../src/mcp-server.mjs', import.meta.url))], env: readerEnv, stderr: 'pipe' });
    let stderr = '';
    client = new Client({ name: 'rollout-rehearsal', version: '1.0.0' });
    await client.connect(transport);
    childPid = transport.pid;
    transport.stderr?.on('data', data => { stderr += data; });
    assert.equal((await client.listTools()).tools.length, 3);
    const call = async (name, args) => {
      const result = await client.callTool({ name, arguments: args });
      assert.notEqual(result.isError, true, result.content?.[0]?.text);
      return JSON.parse(result.content[0].text);
    };
    const matches = await call('match_research_items', { query: 'First.' });
    assert.equal(matches.length, 1);
    assert.ok(matches.every(row => row.project === 'CIC'));
    assert.equal((await call('match_research_items', { query: 'First.', match_threshold: 1 })).length, 0);
    assert.deepEqual(fake.state.requests.filter(request => request.path.endsWith('match_research_items_for_embedding'))[0].input.query_embedding, syntheticEmbedding('First.'));
    const fetched = await call('fetch_document', { document_id: first.id, include_claims: true });
    assert.equal(fetched.document.title, 'Shorter');
    assert.equal(fetched.research_items.length, 1);
    assert.equal(fetched.claims[0].statement, 'Synthetic claim');
    assert.ok(!('claims' in await call('fetch_document', { document_id: first.id })));
    const listed = await call('list_by_status', { status: 'VERIFIED', limit: 1, offset: 0 });
    assert.equal(listed.length, 1);
    assert.equal((await call('list_by_status', { status: 'VERIFIED', offset: 1 })).length, 0);
    const foreign = await client.callTool({ name: 'fetch_document', arguments: { document_id: fake.state.documents.get('RewriteLabs:drive.md').id } });
    assert.equal(foreign.isError, true);
    const absent = await client.callTool({ name: 'fetch_document', arguments: { document_id: '99999999-9999-4999-8999-999999999999' } });
    assert.deepEqual(foreign.content, absent.content);
    const unknown = await client.callTool({ name: 'unknown', arguments: {} });
    assert.equal(unknown.isError, true);
    const reads = fake.state.requests.filter(request => request.path.startsWith('/rest/v1/') && !request.path.endsWith('replace_research_document'));
    assert.ok(reads.length >= 7);
    assert.ok(reads.every(request => request.authorization === `Bearer ${reader}`));
    assert.ok(fake.state.requests.filter(request => request.path === '/api/embed').every(request => request.input.model === 'synthetic-embedding' && request.input.dimensions === 1536));
    assert.equal(stderr, '');
  } finally {
    await client?.close();
    await transport?.close();
    await fake.close();
    await rm(root, { recursive: true, force: true });
  }
  assert.throws(() => process.kill(childPid, 0), { code: 'ESRCH' });
});
